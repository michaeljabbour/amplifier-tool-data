"""End-to-end synthetic scenario proving E1 + F1-replay + E2 + E3 + live-F1 (Plans 1 & 2).

Run: python examples/synthetic_workload.py

Sections
--------
E1      Write a verbatim cell, drop its cache, regenerate byte-for-byte from the log.
        Amendment: relationship event grows provenance without changing payload.
F1      Replay a recorded interpreter output — never calls a model.
E2      Relational + grouped lenses projected CONCURRENTLY over the same kernel.
        Same bytes; two structural shapes; zero interference between lenses.
live-F1 Interpreter with INJECTED deterministic spawn records one atomic batch;
        replay folds the recorded output with ZERO re-invocations of spawn.
E3      IndexLens static fold → IndexCellEvent appended as a first-class Cell →
        regenerated byte-identically WITH provenance; no mutable side-car.
"""

from __future__ import annotations

import concurrent.futures
import json

from amplifier_data.interpreter import Interpreter
from amplifier_data.kernel import InMemoryKernel
from amplifier_data.lenses.grouped import GroupedLens
from amplifier_data.lenses.index import IndexLens
from amplifier_data.lenses.relational import RelationalLens
from amplifier_data.models import Cell, IndexCellEvent, content_address
from amplifier_data.store import AmplifierStore


def main() -> None:
    store = AmplifierStore()

    # -------------------------------------------------------------------------
    # E1: write a verbatim cell, drop its cache, regenerate from the log alone
    # -------------------------------------------------------------------------
    payload = b"Sample drawer: 'the deploy key lives in 1Password vault Eng'"
    ref = store.write_cell(payload, interpreters=("summarizer-agent",))
    store.drop_materialized(ref)
    cell = store.regenerate(ref)
    assert cell.payload == payload, "E1 FAILED: regenerated payload differs"
    print(f"E1 ok: regenerated {len(cell.payload)} bytes byte-for-byte from the log")

    # --- Amendment: a relationship event grows provenance without changing payload ---
    other = store.write_cell(b"Sample drawer: 'Eng vault rotated 2026-06-01'")
    store.relate(ref, other, "supersedes")
    amended = store.regenerate(ref)
    assert amended.payload == payload, "E1 FAILED: amendment changed payload"
    assert len(amended.provenance) == 2, "amendment should grow provenance to 2 events"
    print(f"E1 ok: provenance grew to {len(amended.provenance)} events; identity stable")

    # -------------------------------------------------------------------------
    # F1: replay a recorded interpreter output — never calls a model
    # -------------------------------------------------------------------------
    derived = store.write_interpretation(
        model="claude-sonnet-4-5",
        input_hash=content_address(payload),
        tool_results=(b"1password://vault/Eng",),
        output=b"INTERPRETED: secret stored in 1Password vault 'Eng'",
    )
    replayed = store.regenerate(derived)
    assert replayed.payload.startswith(b"INTERPRETED:"), "F1 FAILED: output not folded"
    nb = len(replayed.payload)
    print(f"F1 ok: replayed recorded interpreter output ({nb} bytes), no model call")

    # -------------------------------------------------------------------------
    # E2: relational + grouped lenses projected CONCURRENTLY over the same kernel
    # -------------------------------------------------------------------------
    # Both lenses fold kernel.all_events() simultaneously in separate threads.
    # Each view exposes the IDENTICAL underlying payload bytes in a structurally
    # different shape, proving that schema/policy is a swappable fold (not baked
    # into the bytes).
    kernel = store.kernel
    rel_lens = RelationalLens()
    grp_lens = GroupedLens()

    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        rel_fut = pool.submit(rel_lens.project, kernel)
        grp_fut = pool.submit(grp_lens.project, kernel)
        rel_view = rel_fut.result()  # list[dict] — flat rows
        grp_view = grp_fut.result()  # dict[str, list[dict]] — grouped by event_type

    # Both views are alive concurrently in this scope.
    assert isinstance(rel_view, list), "E2 FAILED: relational view must be a flat list"
    assert isinstance(grp_view, dict), "E2 FAILED: grouped view must be a dict"
    assert type(rel_view) is not type(grp_view), "E2 FAILED: views must have different types"

    # Same bytes exposed through both structural shapes.
    rel_cw_payloads = {r["payload"] for r in rel_view if r["event_type"] == "cell_write"}
    grp_cw_payloads = {e["payload"] for e in grp_view.get("cell_write", [])}

    assert payload in rel_cw_payloads, "E2 FAILED: payload missing from relational view"
    assert payload in grp_cw_payloads, "E2 FAILED: payload missing from grouped view"
    assert rel_cw_payloads == grp_cw_payloads, (
        "E2 FAILED: cell-write payload bytes must be identical across both lenses"
    )

    # RelationshipEvent is not cell-defining — absent from both views.
    rel_event_types = {r["event_type"] for r in rel_view}
    assert "relationship" not in rel_event_types, (
        "E2 FAILED: RelationshipEvent must not appear in relational view"
    )
    assert "relationship" not in grp_view, (
        "E2 FAILED: RelationshipEvent must not appear in grouped view"
    )

    print(
        f"E2 ok: relational ({len(rel_view)} rows) and grouped "
        f"({sum(len(v) for v in grp_view.values())} entries) "
        "projected concurrently — identical payload bytes, two structural shapes"
    )

    # -------------------------------------------------------------------------
    # live-F1: Interpreter with injected deterministic spawn; zero re-invocations on replay
    # -------------------------------------------------------------------------
    # Write a fresh source cell for the live interpretation.
    source_payload = b"Sample context: agent session history snapshot"
    source_ref = store.write_cell(source_payload)

    spawn_call_count = 0

    def deterministic_spawn(
        cell_ref: str,  # noqa: ARG001 — unused in this deterministic stub
        cell_payload: bytes,  # noqa: ARG001
    ) -> tuple[str, bytes, tuple[bytes, ...]]:
        nonlocal spawn_call_count
        spawn_call_count += 1
        return (
            "claude-sonnet-4-5",
            b"LIVE-INTERP: session summarized for long-term memory",
            (b"tool:read_context", b"tool:write_summary"),
        )

    interpreter = Interpreter(store, deterministic_spawn)
    live_derived_ref = interpreter.interpret(source_ref)
    assert isinstance(live_derived_ref, str), "live-F1 FAILED: interpret must return a Hash"
    assert spawn_call_count == 1, (
        f"live-F1 FAILED: spawn must be called exactly once during record; got {spawn_call_count}"
    )

    # Replay: drop_materialized + re-fold from the log — must NEVER call spawn again.
    spawn_calls_before_replay = spawn_call_count
    replayed_live = store.regenerate(live_derived_ref)
    assert spawn_call_count == spawn_calls_before_replay, (
        f"live-F1 FAILED: spawn called {spawn_call_count - spawn_calls_before_replay} "
        "time(s) during replay — F1 violated"
    )
    assert replayed_live.payload == b"LIVE-INTERP: session summarized for long-term memory", (
        "live-F1 FAILED: replayed payload differs from recorded output"
    )
    print(
        f"live-F1 ok: Interpreter ran spawn once during record; "
        f"replay folded recorded output ({len(replayed_live.payload)} bytes) "
        "with zero spawn re-invocations"
    )

    # -------------------------------------------------------------------------
    # E3: static index fold → IndexCellEvent → first-class Cell → regenerate with provenance
    # -------------------------------------------------------------------------
    # Generate AccessEvents by reading cells via the public API (D4 boundary).
    # store.get_cell() appends exactly one AccessEvent per call.
    store.get_cell(ref)  # three explicit reads of ref
    store.get_cell(ref)
    store.get_cell(ref)
    store.get_cell(other)  # one explicit read of other

    # IndexLens.project() is a PURE fold over kernel.all_events() — zero new events appended.
    index_lens = IndexLens()
    cast_kernel: InMemoryKernel = store.kernel  # type: ignore[assignment]
    log_len_before = len(cast_kernel.all_events())
    index_cell: Cell = index_lens.project(cast_kernel)
    log_len_after = len(cast_kernel.all_events())

    assert log_len_after == log_len_before, (
        "E3 FAILED: IndexLens.project() must not mutate the kernel (pure static fold)"
    )

    # Index payload = canonical JSON access count table (sorted keys for determinism).
    counts: dict[str, int] = json.loads(index_cell.payload.decode("utf-8"))
    assert counts.get(ref, 0) >= 3, (
        f"E3 FAILED: expected ≥3 AccessEvents for ref; got {counts.get(ref, 0)}"
    )
    assert counts.get(other, 0) >= 1, (
        f"E3 FAILED: expected ≥1 AccessEvent for other; got {counts.get(other, 0)}"
    )

    # Provenance carries the defining IndexCellEvent (D2a).
    ice: IndexCellEvent = index_cell.provenance[0]  # type: ignore[assignment]
    assert isinstance(ice, IndexCellEvent), "E3 FAILED: provenance[0] must be the IndexCellEvent"

    # Append the IndexCellEvent: the index is now a FIRST-CLASS CELL in the log
    # (reflexive self-indexing — the store contains its own index as a Cell).
    index_cell_ref = ice.cell_ref
    cast_kernel.append_batch([ice])

    # Materialise the index Cell from the log.
    resolved = cast_kernel.resolve(index_cell_ref)
    assert isinstance(resolved, Cell), "E3 FAILED: kernel.resolve must return a Cell"
    assert resolved.payload == index_cell.payload, (
        "E3 FAILED: materialised payload must equal fold output"
    )

    # Drop materialized cache — regenerate must yield BYTE-IDENTICAL Cell with provenance.
    cast_kernel.drop_materialized(index_cell_ref)
    regenerated_index = cast_kernel.resolve(index_cell_ref)
    assert isinstance(regenerated_index, Cell)
    assert regenerated_index.payload == index_cell.payload, (
        "E3 FAILED: regenerated payload must be byte-identical (deterministic static fold)"
    )
    assert regenerated_index.provenance == index_cell.provenance, (
        "E3 FAILED: regenerated provenance must be identical"
    )
    assert isinstance(regenerated_index.provenance[0], IndexCellEvent), (
        "E3 FAILED: regenerated provenance[0] must be the IndexCellEvent"
    )

    # No mutable side-car: IndexLens has zero instance-level mutable state.
    assert vars(index_lens) == {}, (
        f"E3 FAILED: IndexLens has mutable instance state: {vars(index_lens)!r}"
    )

    print(
        f"E3 ok: IndexLens static fold over {len(counts)} cell(s) indexed; "
        "IndexCellEvent appended as first-class Cell; "
        f"regenerated byte-identically with provenance "
        f"({len(regenerated_index.provenance)} event); "
        "no mutable side-car"
    )

    print(
        "SUCCESS: E1 round-trip + F1 replay + E2 concurrent lenses + "
        "live-F1 Interpreter + E3 static index all proven on the synthetic workload."
    )


if __name__ == "__main__":
    main()
